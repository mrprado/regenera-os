export type CandidateStatus = "candidate" | "registered" | "tested" | "ingesting" | "reaching";
export const STATUS_LABEL: Record<CandidateStatus, string> = { candidate: "Candidate", registered: "Registered (terms recorded)", tested: "Tested (a real call succeeded)", ingesting: "Ingesting (success in 7 days)", reaching: "Reaching OS records" };

/** Pure: status from registry presence, last success and downstream records. */
export function candidateStatus(c: Pick<Candidate, "registryKey">, registry: Set<string>, lastSuccess: Map<string, string>, downstream: Map<string, number>, now = new Date()): CandidateStatus {
  if (!c.registryKey || !registry.has(c.registryKey)) return "candidate";
  if ((downstream.get(c.registryKey) ?? 0) > 0) return "reaching";
  const ok = lastSuccess.get(c.registryKey);
  if (!ok) return "registered";
  return now.getTime() - Date.parse(ok) < 7 * 86_400_000 ? "ingesting" : "tested";
}
